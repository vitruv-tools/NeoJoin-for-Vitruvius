package tools.vitruv.neojoin.vitruv.generator;

import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.inject.Injector;

import org.eclipse.emf.common.util.URI;
import org.eclipse.emf.ecore.plugin.EcorePlugin;
import org.eclipse.emf.ecore.resource.Resource;
import org.eclipse.xtext.generator.IGenerator;
import org.eclipse.xtext.generator.JavaIoFileSystemAccess;
import org.eclipse.xtext.resource.XtextResourceSet;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.FieldSource;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

import javax.tools.DiagnosticCollector;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.SimpleJavaFileObject;
import javax.tools.StandardJavaFileManager;
import javax.tools.StandardLocation;
import javax.tools.ToolProvider;

/**
 * Runs the generator that a Maven build uses on a query over a source meta-model with generated
 * Java classes and compiles the result. This checks that the generated view type fits the
 * expression methods that NeoJoin infers (for example their parameters), which tests with
 * hand-written expression stubs cannot.
 */
class NeoJoinVitruvGeneratorTest {
    private static final String HEADER =
            """
            export compview to "http://example.com/compview"

            import "http://tools.vitruv.change.testutils.metamodels.pcm_mockup"

            """;

    @SuppressWarnings("unused") // used by name in @FieldSource
    private static final List<String> QUERIES =
            List.of(
                    // single source with alias: only the alias is a parameter
                    """
                    from Component c
                    create {
                        c.name
                        shout := c.name.toUpperCase
                    }
                    """,
                    // single source without alias: the implicit 'it' is the only parameter
                    """
                    from Component
                    create {
                        it.name
                        shout := it.name.toUpperCase
                    }
                    """,
                    // several sources: one parameter each
                    """
                    from Component c
                    join PInterface i
                    where c.name == i.name
                    create {
                        c.name
                        both := c.name + i.name
                    }
                    """);

    @TempDir Path tempDir;

    @ParameterizedTest
    @FieldSource("QUERIES")
    void generatedViewTypeCompiles(String query) throws IOException {
        Path input = tempDir.resolve("comp.nj");
        Files.writeString(input, HEADER + query);
        Path output = tempDir.resolve("out");

        generate(input, output);

        List<JavaFileObject> files = new ArrayList<>();
        try (Stream<Path> paths = Files.walk(output.resolve("neojoin"))) {
            for (Path path : paths.filter(p -> p.toString().endsWith(".java")).toList()) {
                files.add(source(path.toString(), Files.readString(path)));
            }
        }
        // generated by the EMF generator in a real build
        files.add(source("neojoin/viewtypes/compview/CompviewPackage.java", PACKAGE_STUB));

        compile(files);
    }

    private static void generate(Path input, Path output) {
        // the generator needs the project of the query to name the genmodel
        EcorePlugin.getPlatformResourceMap()
                .put("project", URI.createFileURI(input.getParent() + "/"));

        // registers the meta-models of the class path (plugin.xml of the test meta-models)
        Injector injector = new NeoJoinVitruvBuildSetup().createInjectorAndDoEMFRegistration();

        XtextResourceSet resourceSet = injector.getInstance(XtextResourceSet.class);
        Resource resource = resourceSet.getResource(URI.createFileURI(input.toString()), true);
        assertTrue(resource.getErrors().isEmpty(), () -> resource.getErrors().toString());

        JavaIoFileSystemAccess fsa = injector.getInstance(JavaIoFileSystemAccess.class);
        fsa.setOutputPath(output.toString());
        injector.getInstance(IGenerator.class).doGenerate(resource, fsa);
    }

    private static void compile(List<JavaFileObject> files) throws IOException {
        JavaCompiler compiler = ToolProvider.getSystemJavaCompiler();
        try (StandardJavaFileManager fileManager =
                compiler.getStandardFileManager(null, null, null)) {
            fileManager.setLocationFromPaths(
                    StandardLocation.CLASS_OUTPUT,
                    List.of(Files.createTempDirectory(null)));
            var diagnostics = new DiagnosticCollector<JavaFileObject>();
            boolean ok =
                    compiler.getTask(
                                    null,
                                    fileManager,
                                    diagnostics,
                                    List.of("-proc:none"),
                                    null,
                                    files)
                            .call();
            assertTrue(ok, diagnostics.getDiagnostics()::toString);
        }
    }

    private static JavaFileObject source(String name, String code) {
        return new SimpleJavaFileObject(
                java.net.URI.create("string:///" + name), JavaFileObject.Kind.SOURCE) {
            @Override
            public CharSequence getCharContent(boolean ignoreEncodingErrors) {
                return code;
            }
        };
    }

    private static final String PACKAGE_STUB =
            """
            package neojoin.viewtypes.compview;

            import org.eclipse.emf.ecore.EAttribute;
            import org.eclipse.emf.ecore.EClass;
            import org.eclipse.emf.ecore.EPackage;
            import org.eclipse.emf.ecore.EReference;

            public interface CompviewPackage extends EPackage {
                CompviewPackage eINSTANCE = null;

                interface Literals {
                    EClass ROOT = null;
                    EClass COMPONENT = null;
                    EReference ROOT__COMPONENTS = null;
                    EAttribute COMPONENT__NAME = null;
                    EAttribute COMPONENT__SHOUT = null;
                    EAttribute COMPONENT__BOTH = null;
                }
            }
            """;
}
